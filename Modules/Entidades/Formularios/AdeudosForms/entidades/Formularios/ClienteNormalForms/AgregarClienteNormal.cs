namespace p_proyect.Modules.Entidades.Formularios.ClienteNormalForms
{
    public partial class AgregarClienteNormal : MaterialForm
    {
        public AgregarClienteNormal()
        {
            InitializeComponent();

            var materialSkinManager = MaterialSkinManager.Instance;
            materialSkinManager.AddFormToManage(this);

            // Fondos blancos
            materialSkinManager.Theme = MaterialSkinManager.Themes.LIGHT;

            // Tema rojizo empresarial
            materialSkinManager.ColorScheme = new ColorScheme(
                Primary.Red800,   // Color principal (barra superior)
                Primary.Red900,   // Dark Primary
                Primary.Red700,   // Light Primary
                Accent.Red200,    // Acento (buttons, sliders)
                TextShade.WHITE   // Color del texto de la barra
            );
        }

        private void AgregarClienteNormal_Load(object sender, EventArgs e)
        {
            Text = "Agregar Cliente Normal";
        }
    }
